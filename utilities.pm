$FreshPorts::Utilities::syslog_init = 0;

sub InitSyslog() {
	if (!$FreshPorts::Utilities::syslog_init) {
		Sys::Syslog::setlogsock('unix');
		Sys::Syslog::openlog('FreshPorts', 'cons, pid', 'user');
		$FreshPorts::Utilities::syslog_init = 1;
	}
}


sub ReportError($;$;$) {
	my $level	= shift;
	my $message	= shift;
	my $die		= shift;

	my $email   = $die;

	_ReportErrorHelper($level, $message, $email, $die);
}

sub ReportErrorEmail($;$;$;$) {
	my $level	= shift;
	my $message	= shift;
	my $email   = shift;
	my $die		= shift;

	_ReportErrorHelper($level, $message, $email, $die);
}

sub _ReportErrorHelper($;$;$;$) {
	my $level	= shift;
	my $message	= shift;
	my $email   = shift;
	my $die		= shift;

	my $suffix = $FreshPorts::Config::scriptpath;

	Sys::Syslog::syslog($level, $message . " ($suffix)");
	print $message . "\n";

	if ($email) {
		SendEmailNotice('dan@langille.org', $message);
	}

	if ($die) {
		die $message . "\n";
	}
}

sub SendEmailNotice($;$) {
	my $To	= shift;
	my $Body	= shift;

	my $hostname = `hostname`;

	$Body = "This message was generated by the FreshPorts Daemon.

The database is $FreshPorts::Config::dbname
at $FreshPorts::Config::FreshPortsURL

$Body

--
hugs+kisses
FreshPorts Daemon
";

	FreshPorts::email::SendMail('FreshPorts Daemon <FreshPorts@FreshPorts.org>', $To, 'FreshPorts error on ' . $hostname, $Body, 'X-FreshPorts-Error: oops');
}

sub trim {
	my $s = shift;

	chomp($s);      # get rid of \n
	$s =~ s/^\s+//; # remove leading spaces
	$s =~ s/\s+$//; # remove trailing spaces

	return $s;
}

sub trim_multiple_to_single {
	my $s = shift;
	
	$s =~ s/\s+/ /g; # Convert multiple blank spaces to single spaces

	return $s;
}

sub TmpFileName($) {
	my $Tag = shift;

	($sec, $min, $hour, $mday, $mon, $year, $wday, $yday, $isdst) = localtime(time);

	$RealMonth = $mon  + 1;
	$RealYear  = $year + 1900;

	my $TmpFileName = '/tmp/FreshPorts.';
	if ($Tag ne '') {
		$TmpFileName .= "$Tag.";
	}
	$TmpFileName .= "$RealYear.$RealMonth.$mday.$hour.$min.$sec.$$";

	return $TmpFileName;
}

