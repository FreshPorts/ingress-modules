sub ReadFile($) {

	my $file = shift;
	my $content;

	open F,$file;
	if (stat F) {
		$content = "";
		while(<F>){
			$content .= $_;
		}
	} else {
		FreshPorts::Utilities::ReportError('warning', "cannot open file $file", 1);
	}

	close F;

	return $content;
}

sub FetchFile($;$;$;$) {
	#
	# fetch a file
	# into the given path
	# returns 1 if fetched.
	# zero otherwise.
	#
	my $DESTDIR		= shift;
	my $SRCDIR		= shift;
	my $FILE			= shift;
	my $REVISION	= shift;

	print "FetchFile $DESTDIR $SRCDIR $FILE $REVISION\n";

	my $result  = 0;

	my $FetchAttempts = 5;

	while ($FetchAttempts) {
		my $command = "sh $FreshPorts::Config::scriptpath/fetch-cvs-file.sh $DESTDIR $SRCDIR $FILE $REVISION 2>&1";
		print "fetch command = '$command'";
		my $FetchResults = `$command`;
		$result = $?;
		print "fetch result = $result\n";
		if (($result >> 8)) {
			#
			# This might be a nice place to retry a fetch, or send an email
			#
			print "that fetch failed.  What do to?\n";
			print "\n\n" . $FetchResults . "\n\n";

			# and we're outta here
			# fetch failed
			# sleep, then try again

			Sys::Syslog::syslog('warning', "sleeping after fetch failed for ($DESTDIR $SRCDIR $FILE)");
			print "fetch failed, sleeping...\n";
			sleep 10;
			$FetchAttempts--;

		} else {
			# fetch worked
			last;
		}
    }

	#
	# if we succeeded in our fetch..
	if ($FetchAttempts) {
		$result = 1;
	}

	return $result;
}

